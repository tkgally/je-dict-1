"""Unit tests for pipeline/priority_lane.py (the polish mode's priority lane).

Run with:  python3 -m unittest build.tests.test_priority_lane
"""
import datetime as dt
import importlib.util
import json
import tempfile
import unittest
from pathlib import Path

_MOD_PATH = Path(__file__).resolve().parents[2] / "pipeline" / "priority_lane.py"
_spec = importlib.util.spec_from_file_location("priority_lane", _MOD_PATH)
pl = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pl)

LINES = ["# Generated by prioritize_polishing.py on 2026-09-27", "# Task: notes", "",
         "00001_a", "00002_b", "00003_c", "00004_d", "00005_e"]


class TestPick(unittest.TestCase):
    def test_skips_headers_recent_and_missing(self):
        exists = {"00001", "00002", "00004", "00005"}
        ids, after = pl.pick(LINES, 1, 2, skip={"00001"}, exists=exists)
        self.assertEqual(ids, ["00002_b", "00004_d"])
        self.assertEqual(after, 8)  # next line to read is 00005_e (line 8)
        ids, _ = pl.pick(LINES, after, 5, skip=set(), exists=exists)
        self.assertEqual(ids, ["00005_e"])

    def test_exhausted(self):
        self.assertEqual(pl.pick(LINES, 9, 3, set(), {"00001"}), ([], 9))

    def test_list_date(self):
        self.assertEqual(pl.list_date(LINES), dt.date(2026, 9, 27))
        self.assertIsNone(pl.list_date(["00001_a"]))


class TestAdvance(unittest.TestCase):
    def test_moves_past_last_read_priority_id(self):
        self.assertEqual(pl.advance(LINES, 4, {"00002", "00004"}), 8)

    def test_ignores_ids_before_cursor(self):
        self.assertEqual(pl.advance(LINES, 6, {"00001"}), 6)


class TestLedger(unittest.TestCase):
    def test_window(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "polished.jsonl"
            p.write_text(json.dumps({"date": "2026-08-01", "id": "00001"}) + "\n" +
                         json.dumps({"date": "2026-09-20", "id": "00002"}) + "\n")
            self.assertEqual(pl.recently_polished(p, 30, dt.date(2026, 9, 27)), {"00002"})
            self.assertEqual(pl.recently_polished(Path(d) / "none.jsonl"), set())


if __name__ == "__main__":
    unittest.main()
